-- 관측 본문은 중복 저장하지 않는다. ID의 크기는 커밋 순서를 의미하지 않는다.
CREATE TABLE observation_delivery (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    observation_batch_id BIGINT NOT NULL REFERENCES observation_batch(id) ON DELETE CASCADE,
    route_version_id BIGINT NOT NULL REFERENCES route_version(id),
    attempt_number INTEGER NOT NULL CHECK (attempt_number > 0),
    kind VARCHAR(16) NOT NULL CHECK (kind IN ('CLEARED', 'STORED')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    acknowledged_at TIMESTAMPTZ
);

CREATE INDEX ix_observation_delivery_pending
    ON observation_delivery (route_version_id, id)
    WHERE acknowledged_at IS NULL;

CREATE INDEX ix_observation_delivery_batch
    ON observation_delivery (observation_batch_id);

CREATE INDEX ix_observation_delivery_acknowledged
    ON observation_delivery (acknowledged_at, id)
    WHERE acknowledged_at IS NOT NULL;
